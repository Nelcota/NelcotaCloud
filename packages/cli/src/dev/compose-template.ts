import { CliError } from '../cli/cli-error'

export const DEFAULT_API_IMAGE = 'ghcr.io/nelcota/nelcota-api:latest'

/** Registry, path, tag or digest characters only: the value lands unquoted in YAML. */
const IMAGE_PATTERN = /^[A-Za-z0-9][A-Za-z0-9._/:@-]*$/

/** `NELCOTA_DEV_API_IMAGE` replaces the published API image (a local build, a pinned tag). */
export function apiImageOf(environment: Record<string, string | undefined>): string {
  const image = environment.NELCOTA_DEV_API_IMAGE?.trim() || DEFAULT_API_IMAGE

  if (IMAGE_PATTERN.test(image) === false) {
    throw new CliError('NELCOTA_DEV_API_IMAGE precisa ser o nome de uma imagem Docker.')
  }

  return image
}

/**
 * The local stack: Postgres, Mailpit, the API and its webhook worker, published on 127.0.0.1
 * only. Ports and secrets come from the `.env` next to it (compose interpolation), so this file
 * holds no secret and is rewritten on every start.
 */
export function renderComposeFile(apiImage: string): string {
  return `# Generated by nelcota dev start: rewritten on every start. Ports and secrets live in .env.
x-database-urls: &database-urls
  CONTROL_PLANE_DATABASE_URL: postgres://nelcota:\${POSTGRES_PASSWORD:?run nelcota dev start}@postgres:5432/nelcota_control
  TENANT_DATABASE_BASE_URL: postgres://nelcota:\${POSTGRES_PASSWORD:?run nelcota dev start}@postgres:5432
  MASTER_KEY_HEX: \${MASTER_KEY_HEX:?run nelcota dev start}

services:
  postgres:
    image: postgres:19
    command: ["postgres", "-c", "max_connections=200"]
    environment:
      POSTGRES_USER: nelcota
      POSTGRES_PASSWORD: \${POSTGRES_PASSWORD:?run nelcota dev start}
      POSTGRES_DB: nelcota_control
    ports:
      - "127.0.0.1:\${NELCOTA_POSTGRES_PORT:-54322}:5432"
    volumes:
      - postgres-data:/var/lib/postgresql
    healthcheck:
      test: ["CMD", "pg_isready", "-h", "127.0.0.1", "-U", "nelcota", "-d", "nelcota_control"]
      interval: 2s
      timeout: 3s
      retries: 30

  mailpit:
    image: axllent/mailpit:v1.34.0
    environment:
      MP_SMTP_AUTH_ACCEPT_ANY: "1"
      MP_SMTP_AUTH_ALLOW_INSECURE: "1"
    ports:
      - "127.0.0.1:\${NELCOTA_MAILPIT_PORT:-54324}:8025"

  api:
    image: ${apiImage}
    depends_on:
      postgres:
        condition: service_healthy
      mailpit:
        condition: service_started
    environment:
      <<: *database-urls
      ADMIN_TOKEN: \${ADMIN_TOKEN:?run nelcota dev start}
      PUBLIC_BASE_URL: http://localhost:\${NELCOTA_API_PORT:-54320}
      BIND_ADDRESS: 0.0.0.0:8080
      SMTP_URL: smtp://mailpit:1025
      EMAIL_FROM: "NelcotaCloud <no-reply@nelcota.local>"
      TENANT_SMTP_ALLOW_ANY_HOST: "true"
      WEBHOOK_ALLOW_PRIVATE_HOSTS: "true"
      DATABASE_PUBLIC_HOST: localhost
      DATABASE_PUBLIC_PORT: "\${NELCOTA_POSTGRES_PORT:-54322}"
      DATABASE_PUBLIC_SSL_MODE: disable
      RUST_LOG: info
    ports:
      - "127.0.0.1:\${NELCOTA_API_PORT:-54320}:8080"
    healthcheck:
      test: ["CMD", "/usr/local/bin/server", "--check-ready"]
      interval: 2s
      timeout: 5s
      start_period: 30s
      retries: 30

  webhook-worker:
    image: ${apiImage}
    command: ["--webhook-worker"]
    depends_on:
      api:
        condition: service_healthy
    environment:
      <<: *database-urls
      WEBHOOK_ALLOW_PRIVATE_HOSTS: "true"
      RUST_LOG: info

volumes:
  postgres-data:
`
}
