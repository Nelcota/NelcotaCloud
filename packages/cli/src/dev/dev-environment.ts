/** The dev stack's `.env`: its compose project, published ports and generated secrets. */
export type DevEnvironment = {
  projectName: string
  apiPort: number
  postgresPort: number
  mailpitPort: number
  postgresPassword: string
  masterKeyHex: string
  adminToken: string
}

/** Produces `bytes` random bytes as hex (`crypto.randomBytes`), injected for tests. */
export type RandomHex = (bytes: number) => string

export const DEFAULT_PORTS = { api: 54320, postgres: 54322, mailpit: 54324 } as const

const MASTER_KEY_BYTES = 32
const ADMIN_TOKEN_BYTES = 32
const POSTGRES_PASSWORD_BYTES = 24

/** Keys of the `.env` file, also read by `docker compose` to fill the template. */
export const ENV_KEYS = {
  projectName: 'COMPOSE_PROJECT_NAME',
  apiPort: 'NELCOTA_API_PORT',
  postgresPort: 'NELCOTA_POSTGRES_PORT',
  mailpitPort: 'NELCOTA_MAILPIT_PORT',
  postgresPassword: 'POSTGRES_PASSWORD',
  masterKeyHex: 'MASTER_KEY_HEX',
  adminToken: 'ADMIN_TOKEN',
} as const satisfies Record<keyof DevEnvironment, string>

/** Fresh secrets for a new stack; hex keeps them safe inside URLs and YAML. */
export function generateDevEnvironment(projectName: string, randomHex: RandomHex): DevEnvironment {
  return {
    projectName,
    apiPort: DEFAULT_PORTS.api,
    postgresPort: DEFAULT_PORTS.postgres,
    mailpitPort: DEFAULT_PORTS.mailpit,
    postgresPassword: randomHex(POSTGRES_PASSWORD_BYTES),
    masterKeyHex: randomHex(MASTER_KEY_BYTES),
    adminToken: randomHex(ADMIN_TOKEN_BYTES),
  }
}

export function renderEnvFile(environment: DevEnvironment): string {
  return [
    '# Generated by nelcota dev start. Ports can be changed here; keep the secrets private.',
    `${ENV_KEYS.projectName}=${environment.projectName}`,
    `${ENV_KEYS.apiPort}=${environment.apiPort}`,
    `${ENV_KEYS.postgresPort}=${environment.postgresPort}`,
    `${ENV_KEYS.mailpitPort}=${environment.mailpitPort}`,
    `${ENV_KEYS.postgresPassword}=${environment.postgresPassword}`,
    `${ENV_KEYS.masterKeyHex}=${environment.masterKeyHex}`,
    `${ENV_KEYS.adminToken}=${environment.adminToken}`,
    '',
  ].join('\n')
}

export function apiUrlOf(environment: DevEnvironment): string {
  return `http://localhost:${environment.apiPort}`
}

export function mailpitUrlOf(environment: DevEnvironment): string {
  return `http://localhost:${environment.mailpitPort}`
}

/** The compose project name from the project folder: `nelcota-<slug>`. */
export function composeProjectNameOf(slug: string): string {
  return `nelcota-${slug.replaceAll('_', '-')}`
}
