use serde::Deserialize;
use utoipa::ToSchema;
use validator::Validate;

use crate::modules::database::admin::table_definition::column_type::ColumnType;
use crate::modules::database::admin::table_definition::object_name::ObjectName;
use crate::modules::database::rejection::database_rejection::DatabaseRejection;
use crate::shared::database::sql_identifier::quote_literal;

/// Defaults written as expressions; any other default is written as a quoted literal, which
/// Postgres converts to the column's type.
const DEFAULT_EXPRESSIONS: [&str; 7] = [
    "now()",
    "gen_random_uuid()",
    "auth.uid()",
    "current_date",
    "current_timestamp",
    "true",
    "false",
];

/// A column of a table created (or added) from the console.
#[derive(Debug, Deserialize, ToSchema, Validate)]
pub struct ColumnDefinition {
    #[validate(length(min = 1, max = 63))]
    pub name: String,
    /// `text`, `varchar`, `smallint`, `integer`, `bigint`, `numeric`, `real`, `double`,
    /// `boolean`, `uuid`, `date`, `time`, `timestamp`, `timestamptz`, `json`, `jsonb`,
    /// `bytea`; append `[]` for an array.
    #[serde(rename = "type")]
    pub type_name: String,
    #[serde(default)]
    pub nullable: bool,
    #[validate(length(max = 1000))]
    /// `now()`, `gen_random_uuid()`, `auth.uid()`, `current_date`, `current_timestamp`,
    /// `true`, `false`, or a literal value.
    pub default: Option<String>,
    /// Numbered automatically (integer types only).
    #[serde(default)]
    pub identity: bool,
    #[serde(default)]
    pub primary_key: bool,
    #[serde(default)]
    pub unique: bool,
    pub references: Option<ColumnReference>,
}

/// A foreign key to a column of another table of the project.
#[derive(Debug, Deserialize, ToSchema)]
pub struct ColumnReference {
    pub table: String,
    pub column: String,
    /// `cascade`, `set_null` or `restrict`; `no action` when absent.
    pub on_delete: Option<String>,
}

impl ColumnDefinition {
    /// `"name" type [GENERATED BY DEFAULT AS IDENTITY] [NOT NULL] [DEFAULT x] [UNIQUE]
    /// [REFERENCES public."t" ("c") ON DELETE ...]`; the primary key is declared by the table.
    pub fn to_sql(&self) -> Result<String, DatabaseRejection> {
        let name = ObjectName::parse(&self.name).map_err(DatabaseRejection::invalid_query)?;
        let column_type =
            ColumnType::parse(&self.type_name).map_err(DatabaseRejection::invalid_query)?;
        let mut sql = format!("{} {}", name.quoted(), column_type.sql());

        if self.identity {
            if column_type.can_be_identity() == false {
                return Err(DatabaseRejection::invalid_query(
                    "only smallint, integer and bigint columns can be numbered automatically",
                ));
            }

            sql.push_str(" GENERATED BY DEFAULT AS IDENTITY");
        }

        if self.nullable == false || self.primary_key {
            sql.push_str(" NOT NULL");
        }

        if let Some(default) = &self.default {
            sql.push_str(&format!(" DEFAULT {}", default_sql(default)));
        }

        if self.unique {
            sql.push_str(" UNIQUE");
        }

        if let Some(reference) = &self.references {
            sql.push_str(&reference.to_sql()?);
        }

        Ok(sql)
    }
}

impl ColumnReference {
    fn to_sql(&self) -> Result<String, DatabaseRejection> {
        let table = ObjectName::parse(&self.table).map_err(DatabaseRejection::invalid_query)?;
        let column = ObjectName::parse(&self.column).map_err(DatabaseRejection::invalid_query)?;
        let on_delete = match self.on_delete.as_deref() {
            None | Some("no_action") => "",
            Some("cascade") => " ON DELETE CASCADE",
            Some("set_null") => " ON DELETE SET NULL",
            Some("restrict") => " ON DELETE RESTRICT",
            Some(other) => {
                return Err(DatabaseRejection::invalid_query(format!(
                    "unknown on_delete action {other}"
                )));
            }
        };

        Ok(format!(
            " REFERENCES {} ({}){on_delete}",
            table.in_public(),
            column.quoted()
        ))
    }
}

fn default_sql(default: &str) -> String {
    let trimmed = default.trim();

    if DEFAULT_EXPRESSIONS.contains(&trimmed) {
        return trimmed.to_owned();
    }

    quote_literal(default)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn column(name: &str, type_name: &str) -> ColumnDefinition {
        ColumnDefinition {
            name: name.to_owned(),
            type_name: type_name.to_owned(),
            nullable: false,
            default: None,
            identity: false,
            primary_key: false,
            unique: false,
            references: None,
        }
    }

    #[test]
    fn writes_identity_defaults_and_references() -> Result<(), DatabaseRejection> {
        let id = ColumnDefinition {
            identity: true,
            primary_key: true,
            ..column("id", "bigint")
        };
        let owner = ColumnDefinition {
            default: Some("auth.uid()".to_owned()),
            ..column("owner_id", "uuid")
        };
        let title = ColumnDefinition {
            nullable: true,
            default: Some("it's new".to_owned()),
            ..column("title", "text")
        };
        let author = ColumnDefinition {
            references: Some(ColumnReference {
                table: "authors".to_owned(),
                column: "id".to_owned(),
                on_delete: Some("cascade".to_owned()),
            }),
            ..column("author_id", "bigint")
        };

        assert_eq!(
            id.to_sql()?,
            "\"id\" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL"
        );
        assert_eq!(
            owner.to_sql()?,
            "\"owner_id\" uuid NOT NULL DEFAULT auth.uid()"
        );
        assert_eq!(title.to_sql()?, "\"title\" text DEFAULT 'it''s new'");
        assert_eq!(
            author.to_sql()?,
            "\"author_id\" bigint NOT NULL REFERENCES public.\"authors\" (\"id\") ON DELETE CASCADE"
        );
        Ok(())
    }

    #[test]
    fn refuses_bad_names_types_and_identities() {
        let identity_text = ColumnDefinition {
            identity: true,
            ..column("code", "text")
        };

        assert!(column("Bad Name", "text").to_sql().is_err());
        assert!(column("ok", "serial").to_sql().is_err());
        assert!(identity_text.to_sql().is_err());
    }
}
