/// Types a column can be created with from the console, by the name the console sends and the
/// SQL written for it. A closed list: the request never writes free text into the DDL.
const COLUMN_TYPES: [(&str, &str); 17] = [
    ("text", "text"),
    ("varchar", "character varying"),
    ("smallint", "smallint"),
    ("integer", "integer"),
    ("bigint", "bigint"),
    ("numeric", "numeric"),
    ("real", "real"),
    ("double", "double precision"),
    ("boolean", "boolean"),
    ("uuid", "uuid"),
    ("date", "date"),
    ("time", "time"),
    ("timestamp", "timestamp"),
    ("timestamptz", "timestamptz"),
    ("json", "json"),
    ("jsonb", "jsonb"),
    ("bytea", "bytea"),
];

/// Types that may be identity columns (`GENERATED BY DEFAULT AS IDENTITY`).
const IDENTITY_TYPES: [&str; 3] = ["smallint", "integer", "bigint"];

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ColumnType {
    sql: &'static str,
    is_array: bool,
}

#[derive(Debug, thiserror::Error, PartialEq, Eq)]
#[error("unsupported column type {0}")]
pub struct UnsupportedColumnType(pub String);

impl ColumnType {
    /// `text`, or `text[]` for an array.
    pub fn parse(name: &str) -> Result<Self, UnsupportedColumnType> {
        let name = name.trim();
        let (base_name, is_array) = match name.strip_suffix("[]") {
            Some(base_name) => (base_name, true),
            None => (name, false),
        };
        let Some((_, sql)) = COLUMN_TYPES.iter().find(|(known, _)| *known == base_name) else {
            return Err(UnsupportedColumnType(name.to_owned()));
        };

        Ok(Self { sql, is_array })
    }

    pub fn sql(&self) -> String {
        match self.is_array {
            true => format!("{}[]", self.sql),
            false => self.sql.to_owned(),
        }
    }

    pub fn can_be_identity(&self) -> bool {
        self.is_array == false && IDENTITY_TYPES.contains(&self.sql)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn writes_known_types_and_arrays() -> Result<(), UnsupportedColumnType> {
        assert_eq!(ColumnType::parse("double")?.sql(), "double precision");
        assert_eq!(ColumnType::parse("text[]")?.sql(), "text[]");
        assert!(ColumnType::parse("bigint")?.can_be_identity());
        assert!(ColumnType::parse("bigint[]")?.can_be_identity() == false);
        Ok(())
    }

    #[test]
    fn refuses_anything_else() {
        for name in ["", "serial", "text; DROP TABLE x", "int[][]", "varchar(20)"] {
            assert!(ColumnType::parse(name).is_err(), "{name} should be refused");
        }
    }
}
